export type QuestionType =
  | 'pattern_table'
  | 'fill_equation'
  | 'visual_choice'
  | 'direct_input'
  | 'visual_cards';

export interface MathQuestion {
  id: string;
  type: QuestionType;
  prompt: string;
  /** For 'pattern_table' (3 stacked rows where the 3rd row has a blank) */
  tableRows?: {
    prefix: string;
    highlight?: string;
    suffix?: string;
    isBlankRow?: boolean;
  }[];
  /** For 'fill_equation' or 'visual_choice' */
  visualKind?:
    | 'blocks_add'
    | 'blocks_sub'
    | 'groups_mul'
    | 'split_div'
    | 'number_balance'
    | 'matrix_grid'
    | 'function_machine'
    | 'trig_triangle';
  visualData?: {
    leftCount: number | string;
    rightCount: number | string;
    operator: '+' | '−' | '×' | '÷' | '^' | '√' | '/' | '=' | '→';
    accentColor: string;
    matrixA?: (number | string)[][];
    matrixB?: (number | string)[][];
    trigTriangle?: {
      opposite: number | string;
      adjacent: number | string;
      hypotenuse: number | string;
      angleLabel: string;
    };
  };
  equationPrefix?: string;
  equationSuffix?: string;
  options: string[];
  correctAnswer: string;
  explanation: string;
}

export interface ArithmeticNode {
  index: number;
  id: string;
  sectionId: number;
  title: string;
  subtitle: string;
  xpReward: number;
  gemsReward: number;
  /** Horizontal offset percentage (-30 to +30) to create the Duolingo S-curve winding path */
  offsetX: number;
  isCheckpoint?: boolean;
  isSkipExam?: boolean;
  targetUnlockNodeIndex?: number;
  questions: MathQuestion[];
}

